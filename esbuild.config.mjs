import esbuild from "esbuild";
import fs from "fs";
import path from "path";
import process from "process";
import { fileURLToPath } from "url";
import { builtinModules, createRequire } from "module";
import postcss from 'esbuild-postcss';
import { normalizeCssHexInDirectory } from "./normalize-css-hex.mjs";

const banner = `/*
THIS IS A GENERATED/BUNDLED FILE BY ESBUILD
if you want to view the source, please visit the github repository of this plugin
*/
`;

const prod = process.argv[2] === "production";

const pluginDir = path.dirname(fileURLToPath(import.meta.url));
process.chdir(pluginDir);

const outdir = path.join(pluginDir, "extension");
if (prod && fs.existsSync(outdir)) {
	fs.rmSync(outdir, { recursive: true, force: true });
}
fs.mkdirSync(outdir, { recursive: true });

function copyWllamaWasm(outputDir) {
	const wllamaPkgDir = path.dirname(
		requireFromPlugin.resolve("@wllama/wllama/package.json")
	);
	const wasmSrc = path.join(wllamaPkgDir, "esm/wasm/wllama.wasm");
	if (!fs.existsSync(wasmSrc)) {
		throw new Error(`Missing wllama WASM binary at ${wasmSrc}`);
	}
	const outWasmDir = path.join(outputDir, "wasm");
	fs.mkdirSync(outWasmDir, { recursive: true });
	fs.copyFileSync(wasmSrc, path.join(outWasmDir, "wllama.wasm"));
}
const requireFromPlugin = createRequire(path.join(pluginDir, "package.json"));
const reactDir = path.dirname(requireFromPlugin.resolve("react/package.json"));
const reactDomDir = path.dirname(requireFromPlugin.resolve("react-dom/package.json"));
const reactAliases = {
	react: reactDir,
	"react-dom": reactDomDir,
	"react-dom/client": path.join(reactDomDir, "client.js"),
	"react/jsx-runtime": path.join(reactDir, "jsx-runtime.js"),
	"react/jsx-dev-runtime": path.join(reactDir, "jsx-dev-runtime.js"),
};

async function buildAiWorkerCode() {
	const result = await esbuild.build({
		entryPoints: [path.join(pluginDir, "workers/ai-worker.ts")],
		bundle: true,
		write: false,
		platform: "browser",
		format: "iife",
		target: "es2022",
		minify: prod,
		legalComments: "none",
		treeShaking: true,
		tsconfig: path.join(pluginDir, "tsconfig.json"),
	});
	return result.outputFiles[0].text;
}

const aiWorkerCode = await buildAiWorkerCode();

const cssPostProcessPlugin = {
	name: "css-post-process",
	setup(build) {
		build.onEnd((result) => {
			if (result.errors.length === 0) {
				postProcessCss(outdir);
			}
		});
	},
};

function postProcessCss(outputDir) {
	const resolvedDir = path.resolve(outputDir);
	const mainCssPath = path.join(resolvedDir, "main.css");
	const stylesPath = path.join(resolvedDir, "styles.css");
	if (fs.existsSync(mainCssPath)) {
		fs.renameSync(mainCssPath, stylesPath);
	}
	normalizeCssHexInDirectory(resolvedDir);
	fs.copyFileSync(
		path.join(pluginDir, "manifest.json"),
		path.join(resolvedDir, "manifest.json")
	);
	copyWllamaWasm(resolvedDir);
}

const context = await esbuild.context({
	banner: {
		js: banner,
	},
	entryPoints: {
		main: path.join(pluginDir, "index.ts"),
	},
	bundle: true,
	external: [
		"obsidian",
		"electron",
		"@codemirror/autocomplete",
		"@codemirror/collab",
		"@codemirror/commands",
		"@codemirror/language",
		"@codemirror/lint",
		"@codemirror/search",
		"@codemirror/state",
		"@codemirror/view",
		"@lezer/common",
		"@lezer/highlight",
		"@lezer/lr",
		"sharp",
		...builtinModules,
	],
	format: "cjs",
	target: "es2022",
	logLevel: "info",
	platform: "browser",
	minify: prod,
	legalComments: "none",
	sourcemap: prod ? false : "inline",
	treeShaking: true,
	outdir: outdir,
	alias: reactAliases,
	plugins: [
		postcss({
			plugins: {
				tailwindcss: {},
				// Desktop-only plugin (Electron/Chromium); skip legacy -moz- duplicates.
				autoprefixer: {
					overrideBrowserslist: ["Chrome >= 111"],
				},
			},
			inject: false,
			extract: true,
		}),
		cssPostProcessPlugin,
	],
	define: {
		'process.env.NODE_ENV': prod ? '"production"' : '"development"',
		'process.env.GITHUB_ACTIONS': JSON.stringify(process.env.GITHUB_ACTIONS || "false"),
		'__AI_WORKER_CODE__': JSON.stringify(aiWorkerCode),
	},
	loader: {
		'.ts': 'ts',
	},
	tsconfig: path.join(pluginDir, "tsconfig.json"),
});

if (prod) {
	await context.rebuild();
	const mainJsPath = path.join(outdir, "main.js");
	const size = fs.statSync(mainJsPath).size;
	const sizeMb = size / (1024 * 1024);
	const syncStandardLimit = 5 * 1024 * 1024;
	console.log(`main.js size: ${sizeMb.toFixed(2)} MB (${size} bytes)`);
	if (size > syncStandardLimit) {
		console.error(
			`main.js exceeds the 5 MB Obsidian Sync Standard limit (${sizeMb.toFixed(2)} MB).`
		);
		process.exit(1);
	}
	process.exit(0);
} else {
	await context.watch();
}
